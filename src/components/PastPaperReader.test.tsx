import { act, fireEvent, render, screen, waitFor, cleanup } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { PastPaperReader } from "./PastPaperReader";
import { DEFAULT_PAPER_READER_CONFIG } from "@/lib/paper-reader-config";

const mocks = vi.hoisted(() => ({ getDocument: vi.fn() }));
vi.mock("pdfjs-dist", () => ({ GlobalWorkerOptions: {}, getDocument: mocks.getDocument }));
beforeEach(() => {
  vi.clearAllMocks();
  vi.stubGlobal("fetch", vi.fn().mockImplementation(async (url: string) => ({ ok: true, headers: new Headers({ "content-type": "application/pdf" }), arrayBuffer: async () => new ArrayBuffer(url.includes("markscheme") ? 10 : 16) })));
  mocks.getDocument.mockImplementation(({ data }: { data: Uint8Array }) => ({ promise: Promise.resolve({ numPages: data.length === 10 ? 10 : 16, getPage: async () => ({ getViewport: ({ scale }: { scale: number }) => ({ width: 595 * scale, height: 842 * scale }), render: () => ({ promise: Promise.resolve(), cancel: vi.fn() }), cleanup: vi.fn() }), destroy: vi.fn() }), destroy: vi.fn() }));
  vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockReturnValue({} as CanvasRenderingContext2D);
  vi.stubGlobal("ResizeObserver", class { observe() {} disconnect() {} });
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute("open", ""); };
  HTMLDialogElement.prototype.close = function () { this.removeAttribute("open"); this.dispatchEvent(new Event("close")); };
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
describe("PastPaperReader", () => {
  it("uses per-paper identity, sources, duration and resets a changed paper", async () => {
    const paper = { id: "0620-2024-s-12", title: "Chemistry 0620 · May / June 2024 · Paper 12", subject: "Chemistry", syllabusCode: "0620", qualification: "Cambridge IGCSE", sessionLabel: "May / June 2024", component: "1", paperName: "Multiple Choice (Core)", variant: "2", durationMinutes: 45, maxMarks: 40, sources: { question: "/archive/12/question", markscheme: "/archive/12/markscheme" }, archiveHref: "/past-papers/igcse-chemistry-0620" };
    const view = render(<PastPaperReader paper={paper} />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(fetch).toHaveBeenCalledWith(paper.sources.question, expect.anything());
    expect(screen.getByText("May / June 2024")).toBeInTheDocument();
    expect(screen.getByText("Paper 1 · Multiple Choice (Core)")).toBeInTheDocument();
    expect(screen.getByText("45 minutes")).toBeInTheDocument();
    expect(screen.getByText("40")).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Past papers" })).toHaveAttribute("href", paper.archiveHref);
    fireEvent.click(screen.getByText("Start timer"));
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("45:00");
    fireEvent.click(screen.getByLabelText("Next page"));
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    await screen.findByRole("img", { name: /Mark scheme, page 1/ });
    expect(fetch).toHaveBeenCalledWith(paper.sources.markscheme, expect.anything());
    expect(screen.getByLabelText("Page number")).toHaveAttribute("max", "10");
    expect(screen.getByRole("link", { name: "Download mark scheme" })).toHaveAttribute("href", paper.sources.markscheme);
    fireEvent.click(screen.getByText("Focus view"));
    expect(screen.getByRole("dialog", { name: `${paper.title} · Focus view` })).toBeInTheDocument();
    view.rerender(<PastPaperReader paper={{ ...paper, id: "0620-2024-s-42", component: "4", paperName: "Theory (Extended)", durationMinutes: 75, maxMarks: 80, sources: { question: "/archive/42/question", markscheme: "/archive/42/markscheme" } }} />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(screen.getByLabelText("Page number")).toHaveValue(1);
    expect(screen.getByText("Optional timer · 75 minutes")).toBeInTheDocument();
    expect(document.body.style.overflow).not.toBe("hidden");
    expect(screen.queryByLabelText("Time remaining")).not.toBeInTheDocument();
    expect(screen.getByText("Paper 42")).toBeInTheDocument();
  });
  it("observes the scroll viewport, updates the current page and keeps canvases bounded", async () => {
    let notify!: IntersectionObserverCallback;
    const disconnect = vi.fn();
    const observe = vi.fn();
    let root: Element | Document | null | undefined;
    vi.stubGlobal("IntersectionObserver", class {
      constructor(callback: IntersectionObserverCallback, options: IntersectionObserverInit) { notify = callback; root = options.root; }
      observe = observe;
      disconnect = disconnect;
    });
    const result = render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(root).toBe(screen.getByRole("tabpanel"));
    expect(observe).toHaveBeenCalledTimes(16);
    const target = document.querySelector('[data-paper-page="8"]')!;
    act(() => notify([{ target, isIntersecting: true, intersectionRect: { height: 600 } } as IntersectionObserverEntry], {} as IntersectionObserver));
    expect(screen.getByRole("spinbutton", { name: "Page number" })).toHaveValue(8);
    await screen.findByRole("img", { name: /Question paper, page 8 of/ });
    expect(screen.getAllByRole("img")).toHaveLength(3);
    expect(screen.queryByRole("img", { name: /Question paper, page 1 of/ })).not.toBeInTheDocument();
    result.unmount();
    expect(disconnect).toHaveBeenCalledTimes(1);
  });
  it("restores independent scroll offsets after QP/MS switches and mode changes", async () => {
    render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    const stage = screen.getByRole("tabpanel");
    stage.scrollTop = 450; fireEvent.scroll(stage);
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    stage.scrollTop = 0; fireEvent.scroll(stage); // loading must not overwrite saved QP position
    await screen.findByRole("img", { name: /Mark scheme, page 1/ });
    expect(document.querySelectorAll("[data-paper-page]")).toHaveLength(10);
    stage.scrollTop = 250; fireEvent.scroll(stage);
    fireEvent.click(screen.getByRole("tab", { name: "Question paper" }));
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(stage.scrollTop).toBe(450);
    fireEvent.change(screen.getByRole("combobox", { name: "Reading mode" }), { target: { value: "single" } });
    fireEvent.change(screen.getByRole("combobox", { name: "Reading mode" }), { target: { value: "scroll" } });
    expect(stage.scrollTop).toBe(450);
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    await screen.findByRole("img", { name: /Mark scheme, page 1/ });
    expect(stage.scrollTop).toBe(250);
  });
  it("keeps the same page and within-page position when Focus view changes page geometry", async () => {
    render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    const stage = screen.getByRole("tabpanel");
    const first = document.querySelector('[data-paper-page="1"]') as HTMLElement;
    let height = 1000;
    Object.defineProperty(first, "offsetHeight", { get: () => height });
    stage.scrollTop = 400; fireEvent.scroll(stage);
    height = 1500;
    fireEvent.click(screen.getByRole("button", { name: "Focus view" }));
    expect(stage.scrollTop).toBe(600);
    height = 1000;
    fireEvent.click(screen.getByRole("button", { name: "Exit focus view" }));
    expect(stage.scrollTop).toBe(400);
  });
  it("validates custom minutes and announces expiry without taking away the PDF", async () => {
    const clock = vi.spyOn(Date, "now").mockReturnValue(1000);
    render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    fireEvent.click(screen.getByText("Custom duration"));
    const minutes = screen.getByRole("spinbutton", { name: "Timer minutes" });
    fireEvent.change(minutes, { target: { value: "0" } });
    fireEvent.click(screen.getByRole("button", { name: "Start timer" }));
    expect(screen.getByRole("alert")).toHaveTextContent("1–360 whole minutes");
    expect(screen.queryByLabelText("Time remaining")).not.toBeInTheDocument();
    fireEvent.change(minutes, { target: { value: "1" } });
    fireEvent.click(screen.getByRole("button", { name: "Start timer" }));
    clock.mockReturnValue(120_000);
    fireEvent(document, new Event("visibilitychange"));
    expect(screen.getByRole("status")).toHaveTextContent("Time is up");
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("0:00");
    expect(screen.queryByRole("button", { name: "Pause timer" })).not.toBeInTheDocument();
    expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "New timer" }));
    expect(screen.getByRole("button", { name: "Start timer" })).toBeInTheDocument();
  });
  it("starts a single optional timer that survives documents, modes and focus", async () => {
    const clock = vi.spyOn(Date, "now").mockReturnValue(1000);
    render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(screen.queryByRole("button", { name: "Pause timer" })).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "Start timer" }));
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("75:00");
    clock.mockReturnValue(61_000);
    fireEvent(document, new Event("visibilitychange"));
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("74:00");
    fireEvent.click(screen.getByRole("button", { name: "Pause timer" }));
    clock.mockReturnValue(301_000);
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    await screen.findByRole("img", { name: /Mark scheme, page 1/ });
    fireEvent.change(screen.getByRole("combobox", { name: "Reading mode" }), { target: { value: "single" } });
    fireEvent.click(screen.getByRole("button", { name: "Focus view" }));
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("74:00");
    fireEvent.click(screen.getByRole("button", { name: "Resume timer" }));
    clock.mockReturnValue(361_000);
    fireEvent(document, new Event("visibilitychange"));
    expect(screen.getByLabelText("Time remaining")).toHaveTextContent("73:00");
    fireEvent.click(screen.getByRole("button", { name: "Finish practice" }));
    await screen.findByRole("img", { name: /Mark scheme, page 1/ });
    expect(screen.getByRole("status")).toHaveTextContent("Practice finished");
    expect(screen.getByRole("img", { name: /Mark scheme, page 1/ })).toBeInTheDocument();
  });
  it("defaults to continuous pages and jumps to a real page slot", async () => {
    render(<PastPaperReader />);
    await screen.findByRole("img", { name: /Question paper, page 1/ });
    expect(screen.getByRole("combobox", { name: "Reading mode" })).toHaveValue("scroll");
    expect(document.querySelectorAll("[data-paper-page]")).toHaveLength(16);
    const stage = screen.getByRole("tabpanel");
    const last = document.querySelector('[data-paper-page="16"]') as HTMLElement;
    Object.defineProperty(last, "offsetTop", { value: 15000 });
    fireEvent.change(screen.getByRole("spinbutton", { name: "Page number" }), { target: { value: "16" } });
    fireEvent.keyDown(screen.getByRole("spinbutton", { name: "Page number" }), { key: "Enter" });
    expect(stage.scrollTop).toBe(15000);
    await screen.findByRole("img", { name: /Question paper, page 16/ });
    expect(screen.getAllByRole("img").length).toBeLessThanOrEqual(3);
    fireEvent.change(screen.getByRole("combobox", { name: "Reading mode" }), { target: { value: "single" } });
    expect(document.querySelectorAll("[data-paper-page]")).toHaveLength(0);
    await screen.findByRole("img", { name: /Question paper, page 16/ });
  });
  it("ignores an aborted older document response after switching tabs", async () => {
    let resolveOld!: (response: Response) => void;
    vi.mocked(fetch).mockImplementationOnce(() => new Promise(resolve => { resolveOld = resolve; }));
    render(<PastPaperReader />);
    const signal = vi.mocked(fetch).mock.calls[0][1]?.signal;
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    expect(signal?.aborted).toBe(true);
    await waitFor(() => expect(screen.getByRole("img", { name: /Mark scheme, page 1/ })).toBeInTheDocument());
    await act(async () => { resolveOld(new Response(new Uint8Array(8), { headers: { "content-type": "application/pdf" } })); });
    await waitFor(() => expect(mocks.getDocument).toHaveBeenCalledTimes(1));
    expect(screen.getByRole("img", { name: /Mark scheme, page 1/ })).toBeInTheDocument();
  });
  it("retries a page render failure without reloading the document", async () => {
    let fail = true;
    const renderPage = vi.fn(() => ({ promise: fail ? Promise.reject(new Error("render failed")) : Promise.resolve(), cancel: vi.fn() }));
    mocks.getDocument.mockImplementationOnce(() => ({ promise: Promise.resolve({ numPages: 16, getPage: async () => ({ getViewport: ({ scale }: { scale: number }) => ({ width: 595 * scale, height: 842 * scale }), render: renderPage }), destroy: vi.fn() }), destroy: vi.fn() }));
    render(<PastPaperReader />);
    const [retry] = await screen.findAllByRole("button", { name: "Retry page" });
    fail = false;
    fireEvent.click(retry);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    expect(fetch).toHaveBeenCalledTimes(1);
  });
  it("switches between fit-width and actual-size PDF rendering", async () => {
    render(<PastPaperReader />);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    fireEvent.change(screen.getByRole("combobox", { name: "PDF zoom" }), { target: { value: "actual" } });
    await waitFor(() => expect(parseFloat(screen.getByRole("img", { name: /Question paper, page 1/ }).style.width)).toBeGreaterThan(790));
    fireEvent.change(screen.getByRole("combobox", { name: "PDF zoom" }), { target: { value: "fit" } });
    await waitFor(() => expect(parseFloat(screen.getByRole("img", { name: /Question paper, page 1/ }).style.width)).toBeCloseTo(100));
  });
  it("recovers from a failed PDF fetch with an explicit retry", async () => {
    vi.mocked(fetch).mockRejectedValueOnce(new Error("offline"));
    render(<PastPaperReader />);
    expect(await screen.findByRole("alert")).toHaveTextContent("The PDF could not be loaded");
    fireEvent.click(screen.getByRole("button", { name: "Retry PDF" }));
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    expect(screen.queryByRole("alert")).not.toBeInTheDocument();
  });
  it("opens native focus view and restores focus and scrolling after Escape", async () => {
    render(<PastPaperReader />);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    const trigger = screen.getByRole("button", { name: "Focus view" }); trigger.focus(); fireEvent.click(trigger);
    const dialog = screen.getByRole("dialog", { name: "Chemistry paper · Focus view" });
    expect(dialog).toHaveAttribute("open");
    expect(document.body.style.overflow).toBe("hidden");
    expect(screen.getByRole("button", { name: "Exit focus view" })).toHaveFocus();
    fireEvent.keyDown(dialog, { key: "Escape" });
    expect(document.body.style.overflow).not.toBe("hidden");
    expect(trigger).toHaveFocus();
    expect(screen.queryByRole("dialog", { name: "Chemistry paper · Focus view" })).not.toBeInTheDocument();
  });
  it("clamps page input and preserves each document's reading position", async () => {
    render(<PastPaperReader />);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    const page = screen.getByRole("spinbutton", { name: "Page number" });
    fireEvent.change(page, { target: { value: "99" } }); fireEvent.blur(page);
    expect(page).toHaveValue(16);
    expect(screen.getByRole("button", { name: "Next page" })).toBeDisabled();
    fireEvent.change(page, { target: { value: "0" } }); fireEvent.keyDown(page, { key: "Enter" });
    expect(page).toHaveValue(1);
    fireEvent.click(screen.getByRole("button", { name: "Next page" }));
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 2/ })).toBeInTheDocument());
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    await waitFor(() => expect(screen.getByRole("img", { name: /Mark scheme, page 1/ })).toBeInTheDocument());
    fireEvent.click(screen.getByRole("tab", { name: "Question paper" }));
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 2/ })).toBeInTheDocument());
  });
  it("switches document tabs and their accessible panel and download", async () => {
    render(<PastPaperReader />);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    fireEvent.click(screen.getByRole("tab", { name: "Mark scheme" }));
    expect(screen.getByRole("tab", { name: "Mark scheme" })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("tabpanel")).toHaveAttribute("aria-labelledby", "paper-tab-markscheme");
    await waitFor(() => expect(screen.getByRole("img", { name: /Mark scheme, page 1/ })).toBeInTheDocument());
    expect(screen.getByRole("spinbutton", { name: "Page number" })).toHaveAttribute("max", "10");
    expect(screen.getByRole("link", { name: /Download mark scheme/ })).toHaveAttribute("href", "/past-papers/preview/document?kind=markscheme");
    fireEvent.keyDown(screen.getByRole("tab", { name: "Mark scheme" }), { key: "ArrowLeft" });
    expect(screen.getByRole("tab", { name: "Question paper" })).toHaveAttribute("aria-selected", "true");
  });
  it("does not invent timing or total marks for an unverified original and links to its own bank", async () => {
    render(<PastPaperReader paper={{ ...DEFAULT_PAPER_READER_CONFIG, id: 'ib-ai-sl-2025-may-p1', subject: 'Mathematics AI', syllabusCode: 'AI', qualification: 'IB Diploma', component: '1', variant: 'TZ2', durationMinutes: null, maxMarks: null, bankSlug: 'ib-ai-sl', reportAvailable: false }} />);
    await waitFor(() => expect(screen.getByRole('img', { name: /Question paper, page 1/ })).toBeInTheDocument());
    expect(screen.queryByRole('button', { name: 'Start timer' })).not.toBeInTheDocument();
    expect(screen.getByText('Duration unverified')).toBeInTheDocument();
    expect(screen.getByText('Marks unverified')).toBeInTheDocument();
    expect(screen.getByRole('link', { name: /Try topic practice/ })).toHaveAttribute('href', 'https://pastpaperprep.com/banks/ib-ai-sl?free=1');
    expect(screen.getByText('Paper 1 · TZ2')).toBeInTheDocument();
    expect(screen.getByRole('navigation', { name: 'Breadcrumb' })).toHaveTextContent('IB Diploma');
  });
  it("does not promise self-marking when paper metadata declares no report", async () => {
    render(<PastPaperReader paper={{ ...DEFAULT_PAPER_READER_CONFIG, reportAvailable: false }} />);
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    expect(screen.queryByRole("link", { name: /Mark this paper/ })).not.toBeInTheDocument();
    expect(screen.queryByText("Finished the paper?")).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Start timer" })).toBeInTheDocument();
  });
  it("introduces the real paper and renders its original PDF", async () => {
    render(<PastPaperReader />);
    expect(screen.getByRole("heading", { name: "Chemistry", level: 1 })).toBeInTheDocument();
    expect(screen.getByText("1 hour 15 minutes")).toBeInTheDocument();
    expect(screen.getByRole("tab", { name: "Question paper" })).toHaveAttribute("aria-selected", "true");
    await waitFor(() => expect(screen.getByRole("img", { name: /Question paper, page 1/ })).toBeInTheDocument());
    expect(screen.getByRole("link", { name: /Download question paper/ })).toHaveAttribute("href", "/past-papers/preview/document?kind=question");
    expect(screen.getByRole("link", { name: /Try topic practice/ })).toHaveAttribute("href", "https://pastpaperprep.com/banks/igcse-chemistry-0620?free=1");
  });
});
