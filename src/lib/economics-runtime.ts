const EXTENSIONS: Record<EconomicsBankSlug, ExtensionArtifact> = {
  "ib-economics-hl": economicsHlMay2026 as unknown as ExtensionArtifact,
  "ib-economics-sl": economicsSlMay2026 as unknown as ExtensionArtifact,
};

const ARTIFACTS: Record<EconomicsBankSlug, RuntimeArtifact> = {
  "ib-economics-hl": economicsHlRuntime as RuntimeArtifact,
  "ib-economics-sl": economicsSlRuntime as RuntimeArtifact,
};
const EXPECTED_COUNTS = { "ib-economics-hl": [111, 42], "ib-economics-sl": [89, 32] } as const;

function assertSafeRelativeAsset(path: string): void {
  const segments = path.split("/");
  if (!path.endsWith(".webp") || path.startsWith("/") || segments.some((segment) => !segment || segment === "." || segment === "..")) {
    throw new Error("Economics runtime contains an unsafe asset path");
  }
}

function validate(bank: EconomicsBankSlug, artifact: RuntimeArtifact): RuntimeArtifact {
  const [questionCount, paperCount] = EXPECTED_COUNTS[bank];
  const seal = artifact.runtimeArtifact;
  if (
    artifact.questions.length !== questionCount ||
    artifact.papers.length !== paperCount ||
    seal.schemaVersion !== "ib-economics-normalized-runtime-v1" ||
    seal.sourceRepository !== "ib-economics-topic-practice" ||
    seal.sourceCommit !== ECONOMICS_RUNTIME_SEALS.sourceCommit ||
    seal.finalClassificationsSha256 !== ECONOMICS_RUNTIME_SEALS.finalClassificationsSha256 ||
    seal.releaseInputsSha256 !== ECONOMICS_RUNTIME_SEALS.releaseInputsSha256 ||
    seal.releaseTaxonomySha256 !== ECONOMICS_RUNTIME_SEALS.releaseTaxonomySha256 ||
    seal.published !== true ||
    seal.assetVerification !== "verified_readback" ||
    seal.storageReceiptSha256 !== ECONOMICS_RUNTIME_SEALS.storageReceiptSha256 ||
    seal.assetManifestSha256 !== ECONOMICS_RUNTIME_SEALS.storageManifestSha256 ||
    seal.storageObjectCount !== ECONOMICS_RUNTIME_SEALS.storageObjectCount ||
    seal.storageByteSize !== ECONOMICS_RUNTIME_SEALS.storageByteSize ||
    seal.contentSha256 !== createHash("sha256").update(JSON.stringify(artifact.questions)).digest("hex")
  ) throw new Error("Economics runtime seal mismatch");
  for (const question of artifact.questions) {
    if (
      question.id !== question.canonicalId ||
      question.bankSlug !== bank ||
      !question.sourceQuestionUrl?.startsWith("https://") ||
      !question.sourceMarkSchemeUrl?.startsWith("https://") ||
      question.classificationEvidence?.finalArtifactSha256 !== ECONOMICS_RUNTIME_SEALS.finalClassificationsSha256 ||
      question.classificationReviewStatus !== "semantic_qa_approved"
    ) throw new Error(`Economics runtime provenance mismatch for ${question.id}`);
    for (const asset of [...(question.questionImages ?? []), ...(question.markschemeImages ?? [])]) assertSafeRelativeAsset(asset);
  }
  return artifact;
}

function validateExtension(bank: EconomicsBankSlug, base: RuntimeArtifact, extension: ExtensionArtifact): ExtensionArtifact {
  const seal = ECONOMICS_MAY_2026_SEALS.banks[bank];
  const artifact = extension.runtimeArtifact;
  if (
    extension.questions.length !== seal.questionCount ||
    extension.papers.length !== seal.paperCount ||
    artifact.schemaVersion !== "ib-economics-2026-may-extension-v1" ||
    artifact.sourceRepository !== ECONOMICS_MAY_2026_SEALS.sourceRepository ||
    artifact.sourceCommit !== ECONOMICS_MAY_2026_SEALS.sourceCommit ||
    artifact.finalClassificationsSha256 !== ECONOMICS_MAY_2026_SEALS.finalClassificationsSha256 ||
    artifact.segmentationManifestSha256 !== ECONOMICS_MAY_2026_SEALS.segmentationManifestSha256 ||
    artifact.releaseTaxonomySha256 !== ECONOMICS_RUNTIME_SEALS.releaseTaxonomySha256 ||
    artifact.siteDataSha256 !== seal.siteDataSha256 ||
    artifact.assetManifestSha256 !== seal.assetManifestSha256 ||
    artifact.assetCount !== seal.assetCount ||
    artifact.assetByteSize !== seal.assetByteSize ||
    artifact.contentSha256 !== seal.contentSha256 ||
    artifact.contentSha256 !== createHash("sha256").update(JSON.stringify(extension.questions)).digest("hex") ||
    artifact.published !== false ||
    artifact.assetVerification !== "pending_upload" ||
    artifact.baseline.contentSha256 !== base.runtimeArtifact.contentSha256 ||
    artifact.baseline.questionCount !== base.questions.length ||
    artifact.baseline.paperCount !== base.papers.length
  ) throw new Error("Economics May 2026 extension seal mismatch");
  const baseIds = new Set(base.questions.map((question) => question.id));
  const seen = new Set<string>();
  for (const question of extension.questions) {
    if (
      question.id !== question.canonicalId ||
      question.bankSlug !== bank ||
      !question.id.startsWith("2026-may-") ||
      baseIds.has(question.id) ||
      seen.has(question.id) ||
      !question.sourceQuestionUrl?.startsWith("https://") ||
      !question.sourceMarkSchemeUrl?.startsWith("https://") ||
      question.classificationEvidence?.finalArtifactSha256 !== ECONOMICS_MAY_2026_SEALS.finalClassificationsSha256 ||
      question.classificationReviewStatus !== "blind_adjudicated_candidate"
    ) throw new Error(`Economics May 2026 provenance mismatch for ${question.id}`);
    seen.add(question.id);
    for (const asset of question.questionImages ?? []) { assertSafeRelativeAsset(asset); if (!asset.startsWith("questions/2026-may-")) throw new Error("Economics May 2026 asset outside its namespace"); }
    for (const asset of question.markschemeImages ?? []) { assertSafeRelativeAsset(asset); if (!asset.startsWith("markschemes/2026-may-")) throw new Error("Economics May 2026 asset outside its namespace"); }
  }
  return extension;
}

/**
 * The sealed 2021-2025 runtime, plus the May 2026 extension only when it has been released
 * (see isEconomicsMay2026Enabled). With the flag off this is exactly the sealed artifact.
 */
export function getEconomicsRuntimeArtifact(bank: EconomicsBankSlug): RuntimeArtifact {
  const base = validate(bank, ARTIFACTS[bank]);
  if (!isEconomicsMay2026Enabled()) return base;
  const extension = validateExtension(bank, base, EXTENSIONS[bank]);
  return {
    ...base,
    questions: [...base.questions, ...extension.questions],
    papers: [...base.papers, ...extension.papers],
  };
}

/** The 2026 extension as shipped (validated), independent of the release flag. For tests and tooling. */
export function getEconomicsMay2026Extension(bank: EconomicsBankSlug): ExtensionArtifact {
  return validateExtension(bank, validate(bank, ARTIFACTS[bank]), EXTENSIONS[bank]);
}

export function getEconomicsRuntimeManifest() {
  return runtimeManifest;
}
