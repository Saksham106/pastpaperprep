#!/usr/bin/env node
// Writes a `<name>.d.json.ts` next to every large JSON file the TypeScript code imports.
// With `allowArbitraryExtensions`, tsc reads that small declaration instead of parsing and
// type-inferring the JSON itself (241 MB of question-bank data pushed type-checking past 6 GB).
// Runtime is unchanged: Next, Vitest and tsx still import the .json file.
//
//   node scripts/generate-json-types.mjs           write / update / remove declarations
//   node scripts/generate-json-types.mjs --check   exit 1 if any declaration is missing or stale
import { existsSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import ts from "typescript";

export const MIN_JSON_BYTES = 200 * 1024;
export const GENERATED_HEADER = "// Generated by scripts/generate-json-types.mjs. Do not edit; run `npm run generate:json-types`.";

const root = join(import.meta.dirname, "..");
const skipDirectories = new Set(["node_modules", ".next", ".git", ".worktrees", ".claude", ".hermes", "out", "build", "public"]);

/** JSON module specifiers in a source file: static, side-effect, dynamic and require imports, comments ignored. */
export function jsonSpecifiers(text) {
  // TypeScript's own scanner, so every import form tsc follows is found (a regex missed commented and side-effect imports).
  return ts.preProcessFile(text, true, true).importedFiles.map((entry) => entry.fileName).filter((name) => name.endsWith(".json"));
}

function walk(directory, visit) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!skipDirectories.has(entry.name)) walk(join(directory, entry.name), visit);
    } else {
      visit(join(directory, entry.name));
    }
  }
}

// allowJs puts imported .mjs/.js files (and their JSON) in the program too, so scan those as well.
function sourceFiles(base) {
  const files = [];
  walk(base, (file) => {
    if (/\.(?:ts|tsx|mts|cts|js|mjs|cjs)$/.test(file) && !file.endsWith(".d.json.ts")) files.push(file);
  });
  return files;
}

/** Absolute paths of JSON files imported by TypeScript sources and big enough to need a declaration. */
export function importedLargeJson(base = root) {
  const found = new Set();
  for (const file of sourceFiles(base)) {
    for (const specifier of jsonSpecifiers(readFileSync(file, "utf8"))) {
      const target = specifier.startsWith("@/")
        ? join(base, "src", specifier.slice(2))
        : specifier.startsWith(".") ? resolve(dirname(file), specifier) : null;
      if (target && existsSync(target) && statSync(target).size >= MIN_JSON_BYTES) found.add(target);
    }
  }
  return [...found].sort();
}

// Shapes mirror how tsc infers a JSON module: widened primitives, literal object keys, and
// array elements merged into one type (keys missing from some elements become optional).
// Lookup tables (more than RECORD_MIN_KEYS keys, none of them identifiers, e.g. question ids)
// become Record<string, T> so the declaration stays small.
export const RECORD_MIN_KEYS = 50;
function shapeOf(value) {
  const shape = { primitives: new Set(), object: null, array: null };
  if (value === null) shape.primitives.add("null");
  else if (Array.isArray(value)) {
    shape.array = { element: null };
    for (const item of value) shape.array.element = merge(shape.array.element, shapeOf(item));
  } else if (typeof value === "object") {
    shape.object = { count: 1, properties: new Map(Object.entries(value).map(([key, item]) => [key, { seen: 1, shape: shapeOf(item) }])) };
  } else shape.primitives.add(typeof value);
  return shape;
}

function merge(left, right) {
  if (!left) return right;
  if (!right) return left;
  const shape = { primitives: new Set([...left.primitives, ...right.primitives]), object: left.object, array: left.array };
  if (right.object) {
    if (!shape.object) shape.object = right.object;
    else {
      const properties = new Map(shape.object.properties);
      for (const [key, property] of right.object.properties) {
        const existing = properties.get(key);
        properties.set(key, existing ? { seen: existing.seen + property.seen, shape: merge(existing.shape, property.shape) } : property);
      }
      shape.object = { count: shape.object.count + right.object.count, properties };
    }
  }
  if (right.array) shape.array = shape.array ? { element: merge(shape.array.element, right.array.element) } : right.array;
  return shape;
}

const isIdentifier = (key) => /^[A-Za-z_$][\w$]*$/.test(key);
const primitiveOrder = ["string", "number", "boolean", "null"];

function render(shape, indent) {
  const parts = primitiveOrder.filter((name) => shape.primitives.has(name));
  if (shape.array) {
    const element = shape.array.element ? render(shape.array.element, indent) : "never";
    parts.push(shape.array.element ? `Array<${element}>` : "never[]");
  }
  if (shape.object) {
    if (shape.object.properties.size === 0) parts.push("{}");
    else if (shape.object.properties.size > RECORD_MIN_KEYS && ![...shape.object.properties.keys()].some(isIdentifier)) {
      const value = [...shape.object.properties.values()].reduce((merged, property) => merge(merged, property.shape), null);
      parts.push(`Record<string, ${render(value, indent)}>`);
    } else {
      const inner = `${indent}  `;
      const lines = [...shape.object.properties].map(([key, property]) => {
        const name = isIdentifier(key) ? key : JSON.stringify(key);
        const optional = property.seen < shape.object.count ? "?" : "";
        return `${inner}${name}${optional}: ${render(property.shape, inner)};`;
      });
      parts.push(`{\n${lines.join("\n")}\n${indent}}`);
    }
  }
  return parts.length ? parts.join(" | ") : "never";
}

/** The TypeScript type tsc would roughly infer for a parsed JSON value. */
export const typeFor = (value) => render(shapeOf(value), "");

export function declarationFor(jsonPath) {
  const type = typeFor(JSON.parse(readFileSync(jsonPath, "utf8")));
  return `${GENERATED_HEADER}\n// Source: ${relative(root, jsonPath)}\ndeclare const data: ${type};\nexport default data;\n`;
}

const declarationPath = (jsonPath) => jsonPath.replace(/\.json$/, ".d.json.ts");

function generatedDeclarations(base = root) {
  const files = [];
  walk(base, (file) => {
    if (file.endsWith(".d.json.ts") && readFileSync(file, "utf8").startsWith(GENERATED_HEADER)) files.push(file);
  });
  return files;
}

/** Declarations that are missing, stale or orphaned, as repo-relative paths. */
export function staleDeclarations(base = root) {
  const expected = new Set();
  const stale = [];
  for (const jsonPath of importedLargeJson(base)) {
    const target = declarationPath(jsonPath);
    expected.add(target);
    if (!existsSync(target) || readFileSync(target, "utf8") !== declarationFor(jsonPath)) stale.push(relative(base, target));
  }
  for (const file of generatedDeclarations(base)) if (!expected.has(file)) stale.push(relative(base, file));
  return stale.sort();
}

function write() {
  const expected = new Set();
  let changed = 0;
  for (const jsonPath of importedLargeJson()) {
    const target = declarationPath(jsonPath);
    expected.add(target);
    const content = declarationFor(jsonPath);
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
      writeFileSync(target, content);
      changed += 1;
    }
  }
  for (const file of generatedDeclarations()) {
    if (!expected.has(file)) {
      unlinkSync(file);
      changed += 1;
    }
  }
  console.log(`JSON declarations: ${expected.size} current, ${changed} written or removed.`);
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  if (process.argv.includes("--check")) {
    const stale = staleDeclarations();
    if (stale.length) {
      console.error(`Out-of-date JSON declarations (run \`npm run generate:json-types\`):\n${stale.join("\n")}`);
      process.exit(1);
    }
    console.log("JSON declarations are current.");
  } else write();
}
