// Regenerates src/content/notes/<course>/index.ts: the course config, its syllabus items, command terms and calculator
// snippets, static imports of every lesson JSON and per-lesson glossary file (merged by mergeGlossary), plus inlined figure SVGs.
// Static imports keep Next's file tracing narrow (no runtime readFile over a broad root).
//
//   node scripts/notes/build-content-index.mjs [--course <slug>]     (default ib-math-aa)
//   node scripts/notes/build-content-index.mjs --all                  every course
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { courseFiles, courseSlugs, notesRoot, parseCourseArg, repoRoot } from "./course.mjs";

export const defaultCourseRoot = join(notesRoot, "ib-math-aa");

const listFiles = (dir, extension) => (existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith(extension)).sort() : []);
const identifier = (file) => `lesson_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;

/** `src/...` paths become `@/...` imports, so the items file can live anywhere under src. */
function importPath(courseRoot, repoPath) {
  if (repoPath.startsWith("src/")) return `@/${repoPath.slice(4)}`;
  const rel = relative(courseRoot, join(repoRoot, repoPath));
  return rel.startsWith(".") ? rel : `./${rel}`;
}

export function buildIndexSource(courseRoot = defaultCourseRoot) {
  const config = JSON.parse(readFileSync(join(courseRoot, "course.json"), "utf8"));
  const lessonFiles = listFiles(join(courseRoot, "lessons"), ".json");
  const figureFiles = listFiles(join(courseRoot, "figures"), ".svg");
  const figures = Object.fromEntries(figureFiles.map((file) => [file.replace(/\.svg$/, ""), readFileSync(join(courseRoot, "figures", file), "utf8").trim()]));
  const sheetFiles = listFiles(join(courseRoot, "cheatsheets"), ".json");
  const sheetId = (file) => `sheet_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
  const glossaryFiles = listFiles(join(courseRoot, "glossary"), ".json");
  const glossaryId = (file) => `glossary_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
  const hasCommandTerms = existsSync(join(courseRoot, "command-terms.json"));
  const hasCalculator = existsSync(join(courseRoot, "calculator.json"));
  return [
    `// GENERATED by scripts/notes/build-content-index.mjs. Do not edit; run \`node scripts/notes/build-content-index.mjs --course ${config.slug}\`.`,
    'import { mergeGlossary } from "@/lib/course-notes/glossary";',
    'import type { CourseConfig } from "@/lib/course-notes/config";',
    'import type { CalculatorSnippets, CheatSheetFile, CommandTerm, GlossaryTerm, ItemsFile, Lesson } from "@/lib/course-notes/types";',
    'import courseJson from "./course.json";',
    `import itemsJson from ${JSON.stringify(importPath(courseRoot, config.items))};`,
    ...(hasCommandTerms ? ['import commandTermsJson from "./command-terms.json";'] : []),
    ...(hasCalculator ? ['import calculatorJson from "./calculator.json";'] : []),
    ...lessonFiles.map((file) => `import ${identifier(file)} from "./lessons/${file}";`),
    ...sheetFiles.map((file) => `import ${sheetId(file)} from "./cheatsheets/${file}";`),
    ...glossaryFiles.map((file) => `import ${glossaryId(file)} from "./glossary/${file}";`),
    "",
    "export const course = courseJson as CourseConfig;",
    "",
    "export const items = itemsJson as ItemsFile;",
    "",
    `export const commandTerms: CommandTerm[] = ${hasCommandTerms ? "commandTermsJson as CommandTerm[]" : "[]"};`,
    "",
    `export const calculatorSnippets: CalculatorSnippets = ${hasCalculator ? "(calculatorJson as { snippets: CalculatorSnippets }).snippets" : "{}"};`,
    "",
    `export const lessons = [${lessonFiles.map(identifier).join(", ")}] as unknown as Lesson[];`,
    "",
    `export const glossary: GlossaryTerm[] = mergeGlossary({${glossaryFiles.map((file) => ` ${JSON.stringify(file.replace(/\.json$/, ""))}: ${glossaryId(file)} as GlossaryTerm[]`).join(",")} });`,
    "",
    `export const cheatSheets: Record<string, CheatSheetFile> = {${sheetFiles.map((file) => ` ${JSON.stringify(file.replace(/\.json$/, ""))}: ${sheetId(file)} as CheatSheetFile`).join(",")} };`,
    "",
    `export const figures: Record<string, string> = ${JSON.stringify(figures, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const slugs = argv.includes("--all") ? courseSlugs() : [parseCourseArg(argv).slug];
  for (const slug of slugs) {
    const { root } = courseFiles(slug);
    writeFileSync(join(root, "index.ts"), buildIndexSource(root));
    console.log("wrote", join(root, "index.ts"));
  }
}
