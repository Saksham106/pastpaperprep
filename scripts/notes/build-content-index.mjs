// Regenerates src/content/notes/<course>/index.ts: static imports of every lesson JSON plus inlined figure SVGs.
// Static imports keep Next's file tracing narrow (no runtime readFile over a broad root).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const defaultCourseRoot = join(repoRoot, "src/content/notes/ib-math-aa");

const listFiles = (dir, extension) => (existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith(extension)).sort() : []);
const identifier = (file) => `lesson_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;

export function buildIndexSource(courseRoot = defaultCourseRoot) {
  const lessonFiles = listFiles(join(courseRoot, "lessons"), ".json");
  const figureFiles = listFiles(join(courseRoot, "figures"), ".svg");
  const figures = Object.fromEntries(figureFiles.map((file) => [file.replace(/\.svg$/, ""), readFileSync(join(courseRoot, "figures", file), "utf8").trim()]));
  const sheetFiles = listFiles(join(courseRoot, "cheatsheets"), ".json");
  const sheetId = (file) => `sheet_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
  return [
    "// GENERATED by scripts/notes/build-content-index.mjs. Do not edit; run `node scripts/notes/build-content-index.mjs`.",
    'import type { CheatSheetFile, Lesson } from "@/lib/course-notes/types";',
    ...lessonFiles.map((file) => `import ${identifier(file)} from "./lessons/${file}";`),
    ...sheetFiles.map((file) => `import ${sheetId(file)} from "./cheatsheets/${file}";`),
    "",
    `export const lessons = [${lessonFiles.map(identifier).join(", ")}] as unknown as Lesson[];`,
    "",
    `export const cheatSheets: Record<string, CheatSheetFile> = {${sheetFiles.map((file) => ` ${JSON.stringify(file.replace(/\.json$/, ""))}: ${sheetId(file)} as CheatSheetFile`).join(",")} };`,
    "",
    `export const figures: Record<string, string> = ${JSON.stringify(figures, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(join(defaultCourseRoot, "index.ts"), buildIndexSource());
  console.log("wrote", join(defaultCourseRoot, "index.ts"));
}
